export function t(key: string, lang: Language): string {
  const translationsForKey = UI_TRANSLATIONS[key];
  if (!translationsForKey) return key;
  return translationsForKey[lang] || translationsForKey['English'] || key;
}

export function getLanguageInfo(lang: Language): LanguageInfo {
  return (
    SUPPORTED_LANGUAGES.find((l) => l.id === lang) ||
    SUPPORTED_LANGUAGES[0]
  );
}
